def footer_ppm(lines, width=960, height=56):
    """Two lines on a black PPM strip; the source picture stays untouched."""
    if len(lines) != 2:
        raise ValueError('Review footer needs two annotation lines')
    scale = min(3, (width-8)//(6*max(1, *map(len, lines))), (height//2-6)//7)
    if scale < 1:
        raise ValueError('Review annotation does not fit the footer')
    pixels = bytearray(width*height*3)
    for line_index, text in enumerate(lines):
        y0 = 4 + line_index*(height//2)
        for index, char in enumerate(text.upper()):
            for y, row in enumerate(GLYPHS.get(char, GLYPHS['?']).split('/')):
                for x, bit in enumerate(row):
                    if bit != '1':
                        continue
                    x0 = 4 + index*6*scale + x*scale
                    for dy in range(scale):
                        at = ((y0+y*scale+dy)*width+x0)*3
                        pixels[at:at+scale*3] = b'\xff'*(scale*3)
    return f'P6\n{width} {height}\n255\n'.encode() + pixels
